"""Preview tray, repeat persistence and activity clocks; uses the shared browser fixtures."""
import asyncio, sys
from pathlib import Path
from playwright.async_api import async_playwright
sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_full as t

async def preview(b, base):
    ctx, pg = await t.new(b, base, 1280, 900)
    await pg.get_by_test_id('demo-oahu').click()
    await pg.get_by_test_id('db-root').wait_for()
    await pg.get_by_test_id('logo').click()
    await pg.get_by_test_id('edit-draft').first.click()
    tray = pg.get_by_test_id('activity-tray')
    cards = tray.get_by_test_id('activity-result')
    titles = await cards.locator('h3').all_text_contents()
    draft = await pg.evaluate('DayBuilder.draftItems().map(i=>i.title)')
    t.ok('tray includes entire draft', all(title in titles for title in draft))
    t.ok('tray has no day badges', await tray.locator('.db-day-num,.badge').count() == 0)
    await pg.get_by_test_id('db-day-2026-11-26').click()
    await pg.get_by_test_id('db-tray-toggle').click()
    chest = pg.get_by_test_id('db-tray')
    parasail = chest.locator('[data-db-id=chest-1]')
    parasail_source = await pg.evaluate("DayBuilder.trayItems().find(i=>i.id==='chest-1').sourceId")
    for chest_id in ('chest-0', 'chest-1', 'chest-2', 'chest-11'):
        old = chest.locator('[data-db-id="'+chest_id+'"]')
        t.ok('chest cross-day guard '+chest_id, await old.get_by_test_id('db-add').is_disabled() and await old.get_by_test_id('db-handle').is_disabled() and await old.get_by_test_id('db-handle').get_attribute('aria-disabled') == 'true' and 'Already in your plan' in await old.inner_text() and await old.get_by_test_id('db-add-again').is_visible())
    t.ok('unscheduled bar enabled', await chest.locator('[data-db-id=chest-bar]').get_by_test_id('db-add').is_enabled())
    before = await pg.evaluate('DayBuilder.draftItems().length')
    await parasail.get_by_test_id('db-add').evaluate('e=>e.click()')
    await parasail.get_by_test_id('db-handle').dispatch_event('pointerdown', {'button':0,'pointerId':1})
    t.ok('disabled chest does nothing', await pg.evaluate('DayBuilder.draftItems().length') == before and await pg.locator('.db-ghost').count() == 0)
    existing_ids = await pg.evaluate('DayBuilder.draftItems().map(i=>i.id)')
    await parasail.get_by_test_id('db-add-again').click()
    copies = await pg.evaluate('ids=>DayBuilder.draftItems().filter(i=>!ids.includes(i.id))', existing_ids)
    t.ok('chest copy has unique instance id and source', len(copies) == 1 and copies[0]['id'].startswith('instance-') and copies[0]['sourceId'] == parasail_source and await pg.evaluate('id=>DayBuilder.draftItems().filter(i=>i.id===id).length', copies[0]['id']) == 1)
    chest_instance = copies[0]['id']
    await pg.reload()
    await pg.get_by_test_id('edit-draft').first.click()
    await pg.get_by_test_id('db-root').wait_for(state='visible')
    t.ok('chest copy reload and import', await pg.evaluate("([id,source])=>DayBuilder.draftItems().some(i=>i.id===id&&i.sourceId===source)&&Object.values(DayBuilder.importDays(DayBuilder.exportState()).days).some(d=>d.items.some(i=>i.id===id&&i.sourceId===source))", [chest_instance, parasail_source]))
    await pg.get_by_test_id('db-day-2026-11-26').click()
    await pg.get_by_test_id('db-day-list').locator('[data-db-id="'+chest_instance+'"]').get_by_test_id('db-remove').click()
    await pg.get_by_test_id('db-day-2026-11-28').click()
    await pg.get_by_test_id('db-day-list').locator('[data-db-source="'+parasail_source+'"]').get_by_test_id('db-remove').click()
    await pg.get_by_test_id('db-day-2026-11-26').click()
    await pg.get_by_test_id('db-tray-toggle').click()
    t.ok('chest last removal enables', await parasail.get_by_test_id('db-add').is_enabled() and await parasail.get_by_test_id('db-handle').is_enabled())
    await pg.get_by_test_id('activity-search').fill('pillbox')
    card = cards.first
    t.ok('duplicate disabled globally', await card.get_by_test_id('activity-add').is_disabled() and await card.get_attribute('draggable') == 'false')
    t.ok('verified photo credit and alt', bool(await card.locator('img').get_attribute('alt')) and await card.locator('.image-label a').count() == 1)
    await pg.get_by_test_id('db-day-2026-11-25').click()
    t.ok('target follows viewed day', await card.get_by_test_id('activity-day').input_value() == '2026-11-25')
    await card.get_by_test_id('activity-add-again').click()
    instance = await pg.evaluate("DayBuilder.draftItems().find(i=>i.id.startsWith('instance-')).id")
    await pg.reload()
    await pg.get_by_test_id('edit-draft').first.click()
    await pg.get_by_test_id('draft-screen').wait_for(state='visible')
    await pg.get_by_test_id('db-root').wait_for(state='visible')
    t.ok('repeat survives reload', await pg.evaluate("(id)=>DayBuilder.draftItems().some(i=>i.id===id)", instance))
    t.ok('repeat survives share import', await pg.evaluate("(id)=>Object.values(DayBuilder.importDays(DayBuilder.exportState()).days).some(d=>d.items.some(i=>i.id===id))", instance))
    await pg.get_by_test_id('db-day-2026-11-25').click()
    row = pg.locator('[data-db-id="'+instance+'"]')
    await row.get_by_test_id('db-expand').click()
    form = row.get_by_test_id('activity-time-form')
    await form.locator('[name=start]').fill('22:00')
    await form.locator('button').click()
    t.ok('default end estimated', 'estimate from default duration' in await row.inner_text())
    if not await form.is_visible():
        await row.get_by_test_id('db-expand').click()
    await form.locator('[name=end]').fill('21:00')
    await form.locator('button').click()
    t.ok('invalid interval accessible', bool(await form.get_by_test_id('activity-time-error').inner_text()) and await form.get_attribute('aria-invalid') == 'true')
    await form.locator('[name=end]').fill('23:00')
    await form.locator('button').click()
    t.ok('manual end saved', '10:00 PM–11:00 PM' == await row.get_by_test_id('db-time').text_content())
    await form.locator('[name=duration]').fill('30')
    await form.locator('button').click()
    t.ok('manual duration saved', '10:00 PM–10:30 PM' == await row.get_by_test_id('db-time').text_content())
    await row.get_by_test_id('db-remove').click()
    await pg.get_by_test_id('db-day-2026-11-28').click()
    original = pg.get_by_test_id('db-day-list').locator('[data-db-source="2026-11-28-1"]')
    await original.get_by_test_id('db-remove').click()
    await pg.get_by_test_id('activity-search').fill('pillbox')
    t.ok('last removal enables add', await cards.first.get_by_test_id('activity-add').is_enabled())
    await pg.get_by_test_id('db-reset').click()
    t.ok('reset restores duplicate guard', await cards.first.get_by_test_id('activity-add').is_disabled())
    await pg.get_by_test_id('db-day-2026-11-26').click()
    t.ok('La Mer fixed', await pg.locator('[data-db-id=lamer]').get_by_test_id('db-time').text_content() == '7:30 PM–9:30 PM')
    photos = pg.locator('[data-db-id=photos]')
    await photos.get_by_test_id('db-expand').click()
    clock = photos.get_by_test_id('activity-time-form')
    await clock.locator('[name=start]').fill('20:00')
    await clock.locator('button').click()
    notes = await photos.get_by_test_id('db-note').all_text_contents()
    t.ok('both sunset conflicts visible', any('After dark' in n for n in notes) and any('Overlaps' in n and 'La Mer' in n for n in notes))
    t.ok('all note references', await photos.evaluate("e=>e.getAttribute('aria-describedby').split(/\\s+/).every(id=>e.querySelector('[id=\"'+id+'\"]'))"))
    t.ok('conflict shown without moving reservation', await pg.get_by_test_id('db-note').count() > 0 and await pg.locator('[data-db-id=lamer]').get_by_test_id('db-time').text_content() == '7:30 PM–9:30 PM')
    t.ok('travel and prep separate', await pg.get_by_test_id('db-travel').count() > 0 and await pg.locator('.db-prep').count() > 0)
    await pg.get_by_test_id('db-day-2026-11-27').click()
    t.ok('Senia fixed', await pg.locator('[data-db-id=senia]').get_by_test_id('db-time').text_content() == '6:00 PM–8:00 PM')
    await ctx.close()

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        await preview(b, (t.SITE/'index.html').resolve().as_uri())
        await b.close()
    assert all(r[1] for r in t.results) and not t.errors
if __name__ == '__main__':
    asyncio.run(main())
